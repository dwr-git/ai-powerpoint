<?php
// studio/api/context.php — ИИ-помощник у выделения («ИИ» возле выделенного текста или фигур и
// «ИИ-помощник…» в контекстном меню слайда). Подключается из assistant.php для запросов
// {mode: "text", op, custom?, extra?, selection, slide?, document}.
//
// Модель видит всю презентацию (текст всех слайдов и заметки), а работает только с выделенным:
// текстом, фигурами или — если ничего не выделено — с текущим слайдом. Большая презентация
// передаётся не целиком: начало, список заголовков слайдов и окно вокруг выделения.

declare(strict_types=1);

/** Сколько токенов презентации (≈ символов / 3,5) отдавать целиком. */
const STUDIO_CONTEXT_TOKENS = 16000;
/** Сколько символов брать по обе стороны от выделения в большой презентации. */
const STUDIO_CONTEXT_WINDOW = 3000;
/** Больше этого текст презентации не принимаем вовсе. */
const STUDIO_CONTEXT_MAX_CHARS = 2000000;

/** Задания операций меню. Ключи — id пунктов меню в studio.js. */
function studio_context_prompt(string $op): ?string
{
    $only = ' Верни ТОЛЬКО результат, без вступлений и пояснений.';
    $slide = ' Это текст слайда презентации: пиши коротко, как пишут на слайдах.';
    $p = [
        'improve' => 'Улучши текст слайда: ясно, ёмко, выразительно, без потери смысла. Сохрани структуру строк (заголовок, пункты), термины и факты.' . $slide . $only,
        'shorten' => 'Сократи текст для слайда: каждая строка — одна мысль, не длиннее 8–10 слов; убери лишнее, сохрани ключевые факты и порядок строк.' . $only,
        'rephrase' => 'Переформулируй текст другими словами, полностью сохранив смысл и число строк.' . $slide . $only,
        'simplify' => 'Упрости текст: короткие фразы, понятные слова, без потери сути.' . $slide . $only,
        'fix_grammar' => 'Исправь орфографические, пунктуационные и грамматические ошибки. Больше ничего не меняй, строки оставь как есть.' . $only,
        'formalize' => 'Перепиши в деловом стиле для презентации руководству.' . $slide . $only,
        'casualize' => 'Перепиши живым разговорным языком для выступления перед широкой аудиторией.' . $slide . $only,
        'to_bullets' => 'Преврати текст в 3–6 тезисов для слайда: каждая строка — «- тезис», не длиннее 10 слов.' . $only,
        'title' => 'Предложи 5 вариантов заголовка слайда (до 7 слов), нумерованным списком.' . $only,
        'speaker_notes' => 'Напиши заметки докладчика к этому слайду: что сказать вслух за 1–2 минуты, связным текстом от первого лица, 80–160 слов. '
            . 'Опирайся на текст слайда и контекст презентации, не выдумывай цифр и фактов.' . $only,
        'outline' => 'Составь по этому тексту план презентации из 4–10 слайдов в Markdown: каждый слайд — строка «# Заголовок», '
            . 'под ней 3–5 строк «- пункт». Без вступлений и заключений вне плана.' . $only,
        'summarize' => 'Кратко перескажи презентацию: о чём она, главные выводы, 4–8 пунктов маркированным списком Markdown.' . $only,
        'questions' => 'Составь 5–8 вопросов, которые слушатели могут задать по этому материалу, и коротко подскажи ответы. Нумерованным списком Markdown.',
        'check_spelling' => 'Проверь орфографию и пунктуацию. Перечисли ошибки списком Markdown: «было → стало». Если ошибок нет, напиши «Ошибок не найдено».',
        'check_slide' => 'Оцени слайд как опытный редактор презентаций: перегруженность, длина строк, ясность заголовка, логика пунктов. '
            . 'Дай 3–6 конкретных советов списком Markdown.',
        'explain' => 'Объясни этот текст простыми словами, с примерами, по шагам.',
    ];
    $langs = ['translate_ru' => 'русский', 'translate_en' => 'английский', 'translate_be' => 'белорусский',
        'translate_de' => 'немецкий', 'translate_fr' => 'французский', 'translate_es' => 'испанский', 'translate_zh' => 'китайский'];
    if (isset($langs[$op])) {
        return "Переведи текст на {$langs[$op]} язык. Сохрани число и порядок строк, термины и стиль." . $only;
    }
    return $p[$op] ?? null;
}

/** Операции, которым без выделения нужна вся презентация. */
function studio_context_whole_doc_ops(): array
{
    return ['summarize', 'questions', 'outline', 'check_spelling'];
}

/** Презентация целиком или (если велика) начало, заголовки слайдов и окно вокруг выделения. */
function studio_context_block(string $doc, string $selected): array
{
    $len = mb_strlen($doc, 'UTF-8');
    if ((int)($len / 3.5) <= STUDIO_CONTEXT_TOKENS) {
        return ['full', "=== ПРЕЗЕНТАЦИЯ ЦЕЛИКОМ ===\n" . $doc . "\n=== КОНЕЦ ПРЕЗЕНТАЦИИ ===\n"];
    }
    $anchor = (int)($len / 2);
    if ($selected !== '') {
        $probe = mb_substr($selected, 0, 200, 'UTF-8');
        $p = mb_strpos($doc, $probe, 0, 'UTF-8');
        if ($p !== false) {
            $anchor = $p + (int)(mb_strlen($selected, 'UTF-8') / 2);
        }
    }
    $start = max(0, $anchor - STUDIO_CONTEXT_WINDOW);
    $end = min($len, $anchor + STUDIO_CONTEXT_WINDOW);
    // Заголовки слайдов: строки «Slide N: …», которые пишет document.text.
    $titles = [];
    foreach (preg_split('/\R/u', $doc) ?: [] as $line) {
        if (preg_match('/^Slide \d+:/u', $line)) {
            $titles[] = '• ' . trim($line);
        }
        if (count($titles) >= 80) {
            break;
        }
    }
    $block = "=== ПРЕЗЕНТАЦИЯ БОЛЬШАЯ: ПОКАЗАНЫ НАЧАЛО, ЗАГОЛОВКИ СЛАЙДОВ И ФРАГМЕНТ ВОКРУГ ВЫДЕЛЕНИЯ ===\n"
        . "--- Начало ---\n" . mb_substr($doc, 0, 800, 'UTF-8') . "\n"
        . "--- Слайды ---\n" . implode("\n", $titles) . "\n"
        . "--- Фрагмент (символы {$start}–{$end} из {$len}) ---\n" . mb_substr($doc, $start, $end - $start, 'UTF-8') . "\n=== КОНЕЦ ===\n";
    return ['windowed', $block];
}

/**
 * Системная инструкция и сообщения для модели по запросу панели.
 * Возвращает [system, messages, contextMode]; при ошибке завершает запрос через studio_fail.
 */
function studio_context_request(array $in): array
{
    $op = is_string($in['op'] ?? null) ? trim($in['op']) : '';
    $custom = is_string($in['custom'] ?? null) ? trim(mb_substr($in['custom'], 0, 4000, 'UTF-8')) : '';
    $extra = is_string($in['extra'] ?? null) ? trim(mb_substr($in['extra'], 0, 2000, 'UTF-8')) : '';
    $selected = is_string($in['selection'] ?? null) ? $in['selection'] : '';
    $slide = is_string($in['slide'] ?? null) ? $in['slide'] : '';
    $doc = is_string($in['document'] ?? null) ? $in['document'] : '';
    if (mb_strlen($doc, 'UTF-8') > STUDIO_CONTEXT_MAX_CHARS) {
        $doc = mb_substr($doc, 0, STUDIO_CONTEXT_MAX_CHARS, 'UTF-8');
    }
    $selected = mb_substr($selected, 0, 60000, 'UTF-8');
    $slide = mb_substr($slide, 0, 20000, 'UTF-8');

    if ($custom !== '') {
        $task = $custom;
    } else {
        $task = studio_context_prompt($op);
        if ($task === null) {
            studio_fail(400, 'Неизвестная операция: ' . $op);
        }
    }
    if ($extra !== '') {
        $task .= "\n\nДополнительное пожелание: " . $extra;
    }

    $system = implode("\n", [
        'Ты — ИИ-помощник, встроенный в редактор презентаций AI-PowerPoint (по возможностям как Microsoft PowerPoint).',
        'Ты видишь текст всей презентации (или его часть), но работаешь только с указанным фрагментом, если он задан.',
        'Отвечай без вступлений вроде «Вот ваш текст:», без извинений и комментариев о себе.',
        'Сохраняй язык исходного текста, если задача — не перевод.',
        'Текст слайдов короткий: строки — это заголовок и пункты; сохраняй разбиение на строки, если задача его не меняет.',
        'Для списков и подзаголовков используй Markdown; обычный текст пиши обычными строками.',
    ]);
    [$mode, $context] = studio_context_block($doc, $selected !== '' ? $selected : $slide);
    if ($selected !== '') {
        $target = "=== ФРАГМЕНТ, С КОТОРЫМ РАБОТАЕМ ===\n" . $selected . "\n=== КОНЕЦ ФРАГМЕНТА ===\n\n"
            . 'Выполни задачу ТОЛЬКО для этого фрагмента; презентация выше — контекст.';
    } elseif (in_array($op, studio_context_whole_doc_ops(), true) && $slide === '') {
        $target = 'Выделения нет: работай со всей презентацией.';
    } elseif ($slide !== '') {
        $target = "=== ТЕКУЩИЙ СЛАЙД ===\n" . $slide . "\n=== КОНЕЦ СЛАЙДА ===\n\n"
            . (in_array($op, studio_context_whole_doc_ops(), true)
                ? 'Выделения нет: работай со всей презентацией; текущий слайд показан для ориентира.'
                : 'Выделения нет: выполни задачу для текущего слайда.');
    } else {
        $target = 'Выделения нет: работай со всей презентацией.';
    }
    $user = ($doc !== '' ? $context . "\n" : '') . $target . "\n\n=== ЗАДАЧА ===\n" . $task;
    return [$system, [['role' => 'user', 'content' => $user]], $mode];
}
